import json
import os
import re
from pathlib import Path
from dotenv import load_dotenv
from openai import OpenAI

# Ensure .env is loaded
dotenv_path = Path(__file__).resolve().parent.parent.parent / ".env"
load_dotenv(dotenv_path=dotenv_path)


def _strip_markdown(text: str) -> str:
    """Strips markdown code fences and whitespace from response text."""
    cleaned = text.strip()
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned, flags=re.IGNORECASE)
        cleaned = re.sub(r"\s*```$", "", cleaned)
    return cleaned.strip()


def review_curriculum(curriculum: dict, assessment: dict) -> dict:
    """
    Reviews the generated curriculum, injects weekly mentor checkpoints,
    and creates a comprehensive capstone project.

    Parameters:
        curriculum (dict): Curriculum generated by build_curriculum().
        assessment (dict): Assessment profile from assess_user().

    Returns:
        dict: Reviewed curriculum with overall_feedback, difficulty_rating,
              weeks (with checkpoints), and final_project.
    """
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        raise ValueError("OPENAI_API_KEY missing from environment or .env file.")

    base_url = os.getenv("OPENAI_BASE_URL")
    client = OpenAI(api_key=api_key, base_url=base_url) if base_url else OpenAI(api_key=api_key)

    system_prompt = (
        "you are a senior bootcamp mentor and curriculum reviewer. Review the curriculum "
        "and add mentorship checkpoints, then return ONLY a raw JSON object with no markdown "
        "and no explanation with these exact keys:\n"
        "- overall_feedback: 2-3 sentences on the curriculum's strengths\n"
        "- difficulty_rating: one of \"too easy\", \"well balanced\", \"too hard\"\n"
        "- weeks: the same weeks list from the curriculum but with one extra key added to each week object:\n"
        "  - checkpoint: a specific question or task the user must complete before moving to the next week. "
        "Must be concrete and testable, not vague. Example: \"Can you add user authentication to your app "
        "and explain how JWT tokens work?\" not \"Review your progress.\"\n"
        "- final_project: a capstone project object with:\n"
        "  - title: name of the final project\n"
        "  - description: what to build in 3-4 sentences\n"
        "  - requirements: list of 5 specific technical requirements\n"
        "  - estimated_hours: integer"
    )

    user_message = (
        f"User Assessment Summary:\n"
        f"- Current Level: {assessment.get('level', '')}\n"
        f"- Recommended Stack: {assessment.get('recommended_stack', '')}\n"
        f"- Summary: {assessment.get('assessment_summary', '')}\n\n"
        f"Full Curriculum to Review:\n"
        f"{json.dumps(curriculum, indent=2)}\n\n"
        f"Add a concrete, testable mentor checkpoint to every single week, "
        f"and generate a final capstone project with 5 technical requirements."
    )

    model_name = os.getenv("OPENAI_MODEL", "gpt-4o-mini")

    try:
        response = client.chat.completions.create(
            model=model_name,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_message},
            ],
            temperature=0.3,
        )
        raw_content = response.choices[0].message.content or ""
    except Exception as e:
        raise RuntimeError(f"Error calling LLM API for curriculum reviewer: {e}") from e

    cleaned_content = _strip_markdown(raw_content)

    try:
        parsed_review = json.loads(cleaned_content)
    except json.JSONDecodeError as e:
        raise ValueError(
            f"Failed to parse reviewer response into JSON: {e}\nRaw response:\n{raw_content}"
        ) from e

    if not isinstance(parsed_review, dict):
        raise ValueError(
            f"Expected a JSON dictionary for reviewed curriculum, but received {type(parsed_review).__name__}."
        )

    required_top_keys = ["overall_feedback", "difficulty_rating", "weeks", "final_project"]
    missing_top = [k for k in required_top_keys if k not in parsed_review]
    if missing_top:
        raise ValueError(f"Review JSON missing required top-level keys: {missing_top}")

    reviewed_weeks = parsed_review.get("weeks", [])
    if not isinstance(reviewed_weeks, list) or len(reviewed_weeks) == 0:
        raise ValueError("Reviewed curriculum must contain a non-empty 'weeks' list.")

    for idx, week_obj in enumerate(reviewed_weeks):
        if not isinstance(week_obj, dict):
            raise ValueError(f"Reviewed week item at index {idx} is not a valid JSON object.")
        if "checkpoint" not in week_obj or not str(week_obj["checkpoint"]).strip():
            raise ValueError(
                f"Week {week_obj.get('week_number', idx + 1)} is missing a testable 'checkpoint'."
            )

    final_proj = parsed_review.get("final_project", {})
    if not isinstance(final_proj, dict):
        raise ValueError("'final_project' must be a valid JSON object.")

    required_capstone_keys = ["title", "description", "requirements", "estimated_hours"]
    missing_capstone = [k for k in required_capstone_keys if k not in final_proj]
    if missing_capstone:
        raise ValueError(f"'final_project' is missing required keys: {missing_capstone}")

    print("Review complete. Checkpoints added.")
    return parsed_review
